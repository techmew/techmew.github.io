'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const src=fs.readFileSync(__dirname+'/pvp-pace-v139.js','utf8'),mod={exports:{}};
new vm.Script(src);vm.runInNewContext(src,{module:mod});const P=mod.exports;
assert.equal(P.MIN_GAP,600000);assert.equal(P.MIN_CPU,5);assert.equal(P.MAX_PER_HOUR,3);assert.equal(P.WINDOW,3600000);
let now=1_000_000;
const p=P.create(null,now);
assert.equal(p.eligibility(now).ready,false,'default OFF');
p.enable(now);
for(let i=1;i<=4;i++)p.completedCpu(now+i*10000);
assert.equal(p.eligibility(now+600000).cpuRemaining,1,'4 CPU fights do not unlock');
p.completedCpu(now+50000);
assert.equal(p.eligibility(now+599999).ready,false,'10 minute minimum strict');
assert.equal(p.eligibility(now+600000).ready,true,'five CPU fights and 10 minutes unlock');
assert.equal(p.encounter(now+600000),true,'first PvP');
assert.equal(p.eligibility(now+1200000).cpuRemaining,5,'CPU quota reset after PvP');
for(let i=0;i<5;i++)p.completedCpu(now+650000+i*20000);
assert.equal(p.eligibility(now+1200000).ready,true,'second slot after gap');
assert.equal(p.encounter(now+1200000),true);
for(let i=0;i<5;i++)p.completedCpu(now+1270000+i*22000);
assert.equal(p.encounter(now+1800000),true,'third encounter admitted');
for(let i=0;i<30;i++)p.completedCpu(now+1860000+i*8000);
assert.equal(p.eligibility(now+2500000).ready,false,'fourth fight blocked by rolling hourly cap');
assert.ok(p.eligibility(now+2500000).hourlyMs>0,'cap gives remaining wait');
assert.equal(p.encounter(now+2500000),false,'cannot bypass rolling hourly cap');
assert.equal(p.eligibility(now+4200001).ready,true,'oldest encounter expires after one hour');
p.disable(now+4200002);
assert.equal(p.eligibility(now+5000000).ready,false,'OFF cannot accept');
const snapshot=p.snapshot();
const restored=P.create(snapshot,now+5000000);
assert.equal(restored.eligibility(now+5000000).ready,false,'OFF survives reload');
restored.enable(now+5000000);
assert.equal(restored.eligibility(now+5000001).ready,false,'re-enable does not instantly bypass pacing');
assert.equal(restored.eligibility(now+5000001).cpuRemaining,5);
assert.equal(restored.eligibility(now+5000001).waitMs>0,true);
const html=fs.readFileSync(__dirname+'/index.html','utf8'),js=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(js);new vm.Script(js);
assert.match(html,/pvp-pace-v139\.js\?v=139/);
assert.match(js,/if\(!match\|\|!match\.done\|\|match\.live/,'NEW CHALLENGER may start only after CPU outcome');
assert.match(js,/pendingChallenge=\{code:data\.code,at:Date\.now\(\),players:0\}/,'match retained without CPU interruption');
assert.match(js,/if\(!m\.live&&activatePendingChallenge\(m\)\)return/,'battle finishes before interruption');
assert.match(js,/pvpPace\.started\(Date\.now\(\)\)/,'actual live start consumes an encounter');
assert.match(js,/pvpPace\.completedCpu\(Date\.now\(\)\)/,'completed CPU rounds count regardless of win');
assert.match(js,/if\(m\.done\)\{advanceAfterWin\(m\);return true\}/,'failed handoff continues to next CPU');
console.log('PVP PACE V139 PASS | 10-min gap, five CPU rounds, 3 per rolling hour, ON/OFF persistence, deferred NEW CHALLENGER');
