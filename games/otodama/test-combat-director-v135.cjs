assert.match(html,/window\.OtodamaDirector\.morphology\(cr\)/,'voice-shaped fighter geometry is used by renderer');
const fighter=(seed,level=20)=>({seed,level,stats:[55,55,55,55,55],voice:{rhythm:55,stable:55,pitch:55,res:55,vol:55},parts:{color:seed%10}});
const winnerByStyle=Array(6).fill(0),totalByStyle=Array(6).fill(0),durations=[],events=new Set();
for(let i=0;i<2400;i++){
 const a=fighter(i+3000),b=fighter(200000+i),styleA=i%6,styleB=Math.floor(i/6)%6;
 const p=[{style:styleA,power:55,mutation:{tier:0}},{style:styleB,power:55,mutation:{tier:0}}];
 const result=D.simulate(a,b,{seed:10007+i*1117,profiles:p,stage:i%6+1});
 assert.ok(result.events.length>0&&result.events.length<=50,'finite fight');
 assert.ok(result.events.every(e=>Number.isFinite(e.damage)&&e.damage>=0&&e.damage<=39&&e.hp.every(v=>Number.isFinite(v)&&v>=0)),'bounded damage and HP');
 assert.ok([0,1].includes(result.winner),'victory defined');
 assert.ok(result.events.every(e=>Number.isFinite(e.distanceAfter)&&e.distanceAfter>=68&&e.distanceAfter<=325),'each turn chooses distance');
 result.events.forEach(e=>events.add(e.kind));
 totalByStyle[styleA]++;winnerByStyle[styleA]+=(result.winner===0);
 durations.push(result.estimatedSeconds);
 if(i%125===0)assert.deepEqual(result,D.simulate(a,b,{seed:10007+i*1117,profiles:p,stage:i%6+1}),'same seed, same combat events');
 const route=D.movement(result.events[0],.49,result.events[0].atk);
 for(const unit of [route.attacker,route.defender])assert.ok(unit.x>=85&&unit.x<=635&&Number.isFinite(unit.y)&&Number.isFinite(unit.rot));
}
const rates=winnerByStyle.map((n,i)=>n/totalByStyle[i]);
assert.ok(rates.every(v=>v>=.39&&v<=.61),'no fighting style should dominate balanced equal-stat round-robin: '+rates);
const avg=durations.reduce((a,b)=>a+b,0)/durations.length;
assert.ok(avg>=15&&avg<=35,'watchable average battle time '+avg);
assert.ok(events.size>=7,'varied actual attack categories: '+[...events]);
const base=fighter(144);
