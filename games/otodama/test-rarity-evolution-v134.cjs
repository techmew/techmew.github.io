assert.equal(evolved.evolutionVoices.length,1);
assert.ok(evolved.stats.some((n,i)=>n>base.stats[i]),'added voice buffs local stats');
assert.equal(evolved.stats.reduce((a,b)=>a+b,0)-base.stats.reduce((a,b)=>a+b,0),14,'high-quality voice adds 14 stat points');
assert.deepEqual([...evolved.evolutionVoices[0].boost].sort((a,b)=>b-a),[8,4,2,0,0]);
assert.equal(evolved.evolutionVoices[0].attackBonus,14);
assert.equal(evolved.evolutionVoices[0].hpBonus,10);
const capped={...base,stats:[99,99,98,99,97]};
const capResult=growth.applyEvolution(capped,sample,strong,'',date);
assert.ok(capResult.stats.every(n=>n<=99),'all five stats cap at 99');
assert.equal(capResult.stats.reduce((a,b)=>a+b,0),495,'overflow distributes to every available stat');
assert.equal(growth.evolutionCombatBonus(capResult).attack,14);
assert.equal(growth.evolutionCombatBonus(capResult).hp,10);
assert.equal(growth.evolutionCombatBonus({...base,evolutionVoices:[{}, {}, {}]}).attack,36,'old saved evolution uses legacy 12% per stage');
assert.equal(base.evolutionVoices,undefined,'original object intact until save succeeds');
assert.equal(evolved.rarity,'S+','evolution does not reroll birth grade');
assert.equal(growth.canEvolve(evolved),false,'next extra sound requires Lv20');
assert.equal(growth.canEvolve({...evolved,level:20}),true);
