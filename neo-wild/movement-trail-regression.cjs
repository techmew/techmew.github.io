"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const world={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,"movement-trail.js"),"utf8"),world);
const trail=world.window.WildMovementTrail,cat={type:"cat",x:100,y:60,r:16};
const emit=(actor,surface,time,land=false)=>trail.record(actor,surface,180,time,0,()=>25,land);
const shapes=(actor,time)=>{const list=[];trail.each(actor,time,(...v)=>list.push(v));return list;};
emit(cat,"earth",0);assert.equal(shapes(cat,0).length,3);
assert(shapes(cat,0).every(v=>v[2]>25));
emit(cat,"hard",.1);assert.equal(shapes(cat,.2).length,3);
assert.equal(shapes(cat,2).length,0);
const deer={...cat,type:"deer"};emit(deer,"earth",2);
assert.equal(shapes(cat,2).length,0);assert.equal(shapes(deer,2).length,2);
deer.flying=true;emit(deer,"water",4);assert.equal(shapes(deer,4).length,0);
deer.flying=false;emit(deer,"water",5);assert.equal(shapes(deer,5).length,2);
emit(deer,"water",7,true);
assert.equal(shapes(deer,7).length,6);assert(shapes(deer,7.25)[0][0]>shapes(deer,7)[0][0]);
for(let k=0;k<100;k++)emit(cat,"earth",9);
assert.equal(shapes(cat,9).length,30);
console.log("Paw, hoof, wake, airborne, dry road, timed landing, expiry and bounded geometry passed.");
